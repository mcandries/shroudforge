"""Compiles the overlay's shaders into ../src/world_depth_spirv.h (SPIR-V words).

Needs glslc (Vulkan SDK) on the PATH or in %VULKAN_SDK%\Bin. The header is
committed: building the overlay does not need glslc.
"""
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SHADERS = [("world_depth.vert", "kWorldDepthVert"), ("world_depth.frag", "kWorldDepthFrag")]


def glslc():
    sdk = os.environ.get("VULKAN_SDK")
    if sdk and os.path.exists(os.path.join(sdk, "Bin", "glslc.exe")):
        return os.path.join(sdk, "Bin", "glslc.exe")
    return "glslc"


def main():
    out = ["// Generated by shaders/compile.py from shaders/*.vert and *.frag: do not edit.", "#pragma once", "",
           "#include <cstdint>", ""]
    for name, symbol in SHADERS:
        words = subprocess.run([glslc(), "-O", "-mfmt=num", "-o", "-", os.path.join(HERE, name)], check=True,
                               capture_output=True, text=True).stdout
        values = [w.strip() for w in words.replace("\n", "").split(",") if w.strip()]
        out.append(f"// {name}")
        out.append(f"inline constexpr uint32_t {symbol}[] = {{")
        for i in range(0, len(values), 8):
            out.append("    " + ", ".join(values[i:i + 8]) + ",")
        out.append("};")
        out.append("")
    with open(os.path.join(HERE, "..", "src", "world_depth_spirv.h"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out))
    print("ok")


if __name__ == "__main__":
    sys.exit(main())
